# ---------------------------------------------------------------- courbes de lumière numérisées
@functools.lru_cache(maxsize=None)
def courbes_binaires() -> dict:
    """{nom: [(phase, flux relatif)]} numérisés depuis les images de l'original."""
    with gzip.open(Path(__file__).with_name('donnees') / 'binaires.json.gz', 'rt', encoding='utf-8') as f:
        d = json.load(f)
    u = float(d['unite'])
    return {k: [(p / u, fl / u) for p, fl in v] for k, v in d['courbes'].items()}
